// Build src/glyphs.js: outlines and metrics of the glyphs the equation
// typesetter (src/equations.js) draws, taken from MathJax's TeX font
// (Computer Modern). Run: bun tools/glyphs.js
//
// Outlines are in font units (1000 per em, y up). A glyph is
// [advance, height, depth, path] with the three metrics in 1/1000 em.

import { createRequire } from 'node:module';

const { TeXFont } = createRequire(import.meta.url)('mathjax-full/js/output/svg/fonts/tex.js');
const chars = TeXFont.defaultChars;

const glyph = (variant, code) => {
  const g = chars[variant]?.[code];

  if(!g?.[3]?.p) throw new Error(`no glyph U+${code.toString(16)} in '${variant}'`);

  const [h, d, w, { p }] = g;

  return [Math.round(w * 1000), Math.round(h * 1000), Math.round(d * 1000), `M${p}Z`];
};

const out = {};
const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const ascii = s => [...s].map(c => c.codePointAt(0));

// roman: digits, letters, the usual operators and punctuation
for(const c of [...range(0x30, 0x39), ...range(0x41, 0x5a), ...range(0x61, 0x7a), ...ascii('+=()[]|/,.:;!%')]) out[String.fromCodePoint(c)] = glyph('normal', c);

// ASCII minus and a middle dot are drawn as the math operators
out['-'] = out['−'] = glyph('normal', 0x2212);
out['·'] = glyph('normal', 0x22c5);
out['×'] = glyph('normal', 0xd7);
out['−'] = glyph('normal', 0x2212);

// math italic letters live at U+1D434.. (h is the planck constant sign)
const italic = (c, base) => (c == 'h' ? 0x210e : base + c.codePointAt(0) - (base == 0x1d434 ? 0x41 : 0x61));

for(const c of 'ABCDEFGHIJKLMNOPQRSTUVWXYZ') out['*' + c] = glyph('normal', italic(c, 0x1d434));
for(const c of 'abcdefghijklmnopqrstuvwxyz') out['*' + c] = c == 'h' ? glyph('normal', 0x210e) : glyph('normal', italic(c, 0x1d44e));

// greek: italic lowercase (U+1D6FC..), upright capitals
const lower = 'αβγδεζηθικλμνξοπρςστυφχψω';

// (lower case is italic only, as in TeX; the typesetter falls back to it)
[...lower].forEach((c, i) => (out['*' + c] = glyph('normal', 0x1d6fc + i)));
for(const c of 'ΓΔΘΛΞΠΣΥΦΨΩ') out[c] = glyph('normal', c.codePointAt(0));

// stretchy delimiters in the five TeX sizes (1, 1.2, 1.8, 2.4, 3 em)
const SIZES = ['normal', '-smallop', '-largeop', '-size3', '-size4'];
const delims = {};

for(const c of ['(', ')', '[', ']', '√']) delims[c] = SIZES.map(v => glyph(v, c.codePointAt(0)));

const lines = Object.entries(out).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);
const dl = Object.entries(delims).map(([k, v]) => `  ${JSON.stringify(k)}: ${JSON.stringify(v)},`);

await Bun.write(
  new URL('../src/glyphs.js', import.meta.url),
  `// Generated by tools/glyphs.js from the MathJax TeX font, do not edit.
// Glyph: [advance, height, depth, path], metrics in 1/1000 em, outline y up.
// Keys: the character, or '*' + character for the math italic form.

export const GLYPHS = {
${lines.join('\n')}
};

// Delimiter sizes 0..4 (1, 1.2, 1.8, 2.4, 3 em) of ( ) [ ] and the radical.
export const DELIMS = {
${dl.join('\n')}
};
`,
);

console.log(`${Object.keys(out).length} glyphs, ${Object.keys(delims).length} delimiters`);
